_CACHE = {}


def grille(code):
    """
    But : grille d'une icône (trophée par défaut pour un succès inconnu).
    Entrée : code (str). Sortie : (list de str) ou None si le code est inconnu.
    """
    return GRILLES.get(code)


def surface_icone(code, couleur, echelle=2, defaut=None):
    """
    But : image (avec transparence) d'une icône, mise en cache.
    Entrées : code (str) ; couleur (tuple RVB) ; echelle (int) : taille d'un pixel ;
              defaut (list de str ou None) : grille si le code est inconnu.
    Sortie : (pygame.Surface) ou None si le code est inconnu et sans défaut.
    """
    motif = GRILLES.get(code, defaut)
    if motif is None:
        return None
    cle = (code if code in GRILLES else id(defaut), tuple(couleur), echelle)
    if cle in _CACHE:
        return _CACHE[cle]
    teintes = {"X": tuple(couleur), "o": melanger(couleur, (255, 255, 255), 0.65),
               "d": attenuer(couleur, 0.3)}
    cote = TAILLE * echelle + 2
    image = pygame.Surface((cote, cote), pygame.SRCALPHA)
    cellules = [(c, l, car) for l, ligne in enumerate(motif) for c, car in enumerate(ligne)
                if car in teintes]
    # Contour sombre (1 px autour de chaque cellule), puis les cellules.
    for c, l, _ in cellules:
        for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            image.fill(CONTOUR, (1 + c * echelle + dx, 1 + l * echelle + dy, echelle, echelle))
    for c, l, car in cellules:
        image.fill(teintes[car], (1 + c * echelle, 1 + l * echelle, echelle, echelle))
    _CACHE[cle] = figer(image)
    return image


def dessiner_icone(image, code, centre, couleur, echelle=2, lueur=False, largeur=None,
                   defaut=None):
    """
    But : dessiner une icône centrée.
    Entrées : image ; code (str) ; centre (x, y) ; couleur ; echelle (int) ;
              lueur (bool) : halo néon ; largeur (int ou None) : écrasement
              horizontal (capsule qui tourne) ; defaut : grille de secours.
    Sortie : (bool) True si une icône a été dessinée.
    """
    icone = surface_icone(code, couleur, echelle, defaut)
    if icone is None:
        return False
    if largeur is not None and largeur < icone.get_width():
        if largeur < 3:
            return True
        icone = pygame.transform.scale(icone, (largeur, icone.get_height()))
    rect = icone.get_rect(center=(int(centre[0]), int(centre[1])))
    if lueur:
        halo = halo_rect(rect.w, rect.h, attenuer(couleur, 0.45), rayon=6)
        image.blit(halo, (rect.x - 12, rect.y - 12), special_flags=pygame.BLEND_RGB_ADD)
    image.blit(icone, rect)
    return True
